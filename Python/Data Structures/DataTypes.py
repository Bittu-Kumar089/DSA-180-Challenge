# Python Data Types Example

# 1. Integer (int)
age = 21
print("Integer:", age, type(age))

# 2. Float (float)
salary = 55000.75
print("Float:", salary, type(salary))

# 3. String (str)
name = "Bittu Kumar"
print("String:", name, type(name))

# 4. Boolean (bool)
is_student = True
print("Boolean:", is_student, type(is_student))

# 5. List (list) - Ordered, Mutable
fruits = ["Apple", "Banana", "Mango"]
print("List:", fruits, type(fruits))

# 6. Tuple (tuple) - Ordered, Immutable
colors = ("Red", "Green", "Blue")
print("Tuple:", colors, type(colors))

# 7. Set (set) - Unordered, Unique Elements
numbers = {1, 2, 3, 4, 5}
print("Set:", numbers, type(numbers))

# 8. Dictionary (dict) - Key-Value Pair
student = {
    "Name": "Bittu",
    "Age": 21,
    "Course": "B.Tech CSE"
}
print("Dictionary:", student, type(student))

# 9. Complex Number (complex)
complex_num = 4 + 5j
print("Complex:", complex_num, type(complex_num))

# 10. NoneType (None)
value = None
print("NoneType:", value, type(value))
